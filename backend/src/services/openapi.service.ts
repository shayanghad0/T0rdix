import { writeLog } from "./log.service";
import type { JwtUser } from "../utils/jwt";

/**
 * OpenAPI / Swagger import + export.
 *
 * Import supports both OpenAPI 3.x and Swagger 2.0 JSON documents. Every
 * (path, method) pair becomes a mock endpoint; a representative response body
 * is synthesized from `example`, `examples`, or the JSON schema.
 */

type JsonObject = Record<string, unknown>;

function asObject(value: unknown): JsonObject {
  return typeof value === "object" && value !== null ? (value as JsonObject) : {};
}

function firstResponseStatusCode(responses: JsonObject): number {
  for (const code of ["201", "200", "202", "default", "204"]) {
    if (code in responses) return Number.parseInt(code, 10) || 200;
  }
  const keys = Object.keys(responses);
  const numeric = keys.map((key) => Number.parseInt(key, 10)).find((value) => Number.isFinite(value));
  return numeric && numeric >= 200 && numeric < 400 ? numeric : 200;
}

function sampleFromSchema(schema: unknown, depth = 0): unknown {
  if (depth > 6) return null;
  const obj = asObject(schema);
  if ("example" in obj) return obj.example;
  if ("default" in obj) return obj.default;
  if ("enum" in obj && Array.isArray(obj.enum) && obj.enum.length > 0) return obj.enum[0];

  const type = String(obj.type ?? "object");
  switch (type) {
    case "object": {
      const properties = asObject(obj.properties);
      const out: JsonObject = {};
      for (const [key, propSchema] of Object.entries(properties)) {
        out[key] = sampleFromSchema(propSchema, depth + 1);
      }
      return out;
    }
    case "array": {
      const items = obj.items ?? {};
      return [sampleFromSchema(items, depth + 1)];
    }
    case "string": {
      if (obj.format === "date-time") return new Date().toISOString();
      if (obj.format === "uuid") return newId();
      if (obj.format === "email") return "user@t0rdix.dev";
      if (obj.format === "uri") return "https://t0rdix.dev";
      const name = String(obj.title ?? "value");
      return name.charAt(0).toUpperCase() + name.slice(1);
    }
    case "integer":
    case "number":
      return 1;
    case "boolean":
      return true;
    default:
      return null;
  }
}

/** Build a plausible response body for an operation from OpenAPI 3 content. */
function bodyFromOpenApi3(operation: JsonObject): string {
  const responses = asObject(operation.responses);
  const code = firstResponseStatusCode(responses);
  const response = asObject(responses[String(code)] ?? Object.values(responses)[0]);
  const content = asObject(response.content);
  const json = asObject(content["application/json"]);
  const schema = json.schema;

  let payload: unknown = undefined;
  if ("example" in json) payload = json.example;
  else if (schema) payload = sampleFromSchema(schema);

  if (payload === undefined) {
    payload = code >= 400 ? { error: "SAMPLE_ERROR" } : { data: "Sample response generated by T0rdix" };
  }
  return JSON.stringify(payload, null, 2);
}

/** Swagger 2 variant uses `schema` directly on responses. */
function bodyFromSwagger2(operation: JsonObject): string {
  const responses = asObject(operation.responses);
  const code = firstResponseStatusCode(responses);
  const response = asObject(responses[String(code)] ?? Object.values(responses)[0]);
  const payload = "schema" in response ? sampleFromSchema(response.schema) : { data: "Sample response" };
  return JSON.stringify(payload ?? { data: "Sample response" }, null, 2);
}

export interface ImportReport {
  apiName: string;
  endpointsCreated: number;
  collectionCreated?: string;
  warnings: string[];
}

export async function importOpenApi(
  projectId: string,
  user: JwtUser,
  rawDocument: string,
): Promise<ImportReport> {
  let document: JsonObject;
  try {
    document = asObject(JSON.parse(rawDocument));
  } catch {
    throw ApiError.badRequest(
      "The document is not valid JSON. Export your spec as openapi.json / swagger.json and try again.",
    );
  }

  const warnings: string[] = [];

  const info = asObject(document.info);
  const apiName = (String(info.title ?? "Imported API").slice(0, 80)) || "Imported API";
  const version = String(info.version ?? "1.0.0");

  const isSwagger2 = String(document.swagger ?? "").startsWith("2");

  // Swagger 2.0 may declare a global basePath; OpenAPI 3 paths are root-relative.
  const basePath = isSwagger2 ? String(document.basePath ?? "") : "";

  const paths = asObject(document.paths);
  const pathKeys = Object.keys(paths);
  if (pathKeys.length === 0) {
    throw ApiError.badRequest("No `paths` found in the document — is this an OpenAPI/Swagger file?");
  }

  const allowed: HttpMethod[] = ["GET", "POST", "PUT", "PATCH", "DELETE"];
  const endpoints: ApiEndpoint[] = [];

  for (const pathKey of pathKeys) {
    const pathItem = asObject(paths[pathKey]);
    for (const method of allowed) {
      const operation = asObject(pathItem[method.toLowerCase()]);
      if (Object.keys(operation).length === 0) continue;

      const summary = String(operation.summary ?? operation.operationId ?? `${method} ${pathKey}`);
      const fullPath = `${basePath}${pathKey}`.replace(/\/+/g, "/").replace(/\/$/, "") || "/";

      // Convert OpenAPI path params {id} -> :id segment style.
      const t0rdixPath = fullPath.replace(/\{([^}]+)\}/g, ":$1");

      const responseBody = isSwagger2 ? bodyFromSwagger2(operation) : bodyFromOpenApi3(operation);

      endpoints.push({
        id: newId(),
        method,
        path: t0rdixPath,
        statusCode: firstResponseStatusCode(asObject(operation.responses)),
        delayMs: 0,
        description: summary,
        headers: { "content-type": "application/json" },
        responseBody,
        errorMode: "none",
        errorStatus: 500,
        enabled: true,
        createdAt: nowIso(),
        updatedAt: nowIso(),
      });

      if (t0rdixPath.includes(":")) {
        warnings.push(`${method} ${t0rdixPath}: :param segments are matched as wildcards.`);
      }
    }
  }

  const api: MockApi = {
    id: newId(),
    projectId,
    name: `${apiName} (${version})`,
    description: String(info.description ?? "").slice(0, 400),
    endpoints,
    createdAt: nowIso(),
    updatedAt: nowIso(),
  };
  await db.apis.insert(api);

  // Also create a sample collection with GET requests for quick testing.
  const collectionId = newId();
  await db.collections.insert({
    id: collectionId,
    projectId,
    name: `${apiName} — imported requests`,
    description: "Auto-generated from OpenAPI import.",
    requests: endpoints
      .filter((endpoint) => endpoint.method === "GET")
      .slice(0, 25)
      .map((endpoint) => ({
        id: newId(),
        name: endpoint.description || `${endpoint.method} ${endpoint.path}`,
        method: endpoint.method,
        url: `http://localhost:5000/api/mock/${projectId}${endpoint.path.replace(/:[^/]+/g, "1").replace(/\/:/, "/1")}`,
        headers: {},
        params: {},
        body: "",
        auth: { type: "none" as const },
        createdAt: nowIso(),
        updatedAt: nowIso(),
      })),
    createdAt: nowIso(),
    updatedAt: nowIso(),
  });

  await writeLog({
    type: "user",
    actor: user.email,
    userId: user.id,
    projectId,
    action: "openapi.imported",
    meta: { api: apiName, endpoints: endpoints.length },
  });

  return {
    apiName: api.name,
    endpointsCreated: endpoints.length,
    collectionCreated: `${apiName} — imported requests`,
    warnings,
  };
}

/** Generate an OpenAPI 3 document from the project's mock endpoints. */
export async function exportOpenApi(projectId: string, projectName: string): Promise<JsonObject> {
  const apis = await db.apis.find((api) => api.projectId === projectId);

  const pathsObject: JsonObject = {};
  for (const api of apis) {
    for (const endpoint of api.endpoints) {
      // OpenAPI path style: :id -> {id}
      const openApiPath = endpoint.path.replace(/:([A-Za-z0-9_]+)/g, "{$1}");
      const item = asObject(pathsObject[openApiPath]);
      item[endpoint.method.toLowerCase()] = {
        summary: endpoint.description || `${endpoint.method} ${endpoint.path}`,
        tags: [api.name],
        responses: {
          [String(endpoint.statusCode)]: {
            description: "Mocked response",
            content: { "application/json": { example: safeParse(endpoint.responseBody) } },
          },
          ...(endpoint.errorMode !== "none"
            ? { [String(endpoint.errorStatus)]: { description: "Simulated error" } }
            : {}),
        },
      };
      pathsObject[openApiPath] = item;
    }
  }

  return {
    openapi: "3.0.3",
    info: {
      title: projectName,
      description: `Generated by T0rdix from project ${projectName}.`,
      version: "1.0.0",
    },
    servers: [{ url: `http://localhost:5000/api/mock/${projectId}` }],
    paths: pathsObject,
  };
}

function safeParse(raw: string): unknown {
  try {
    return JSON.parse(raw);
  } catch {
    return raw || "";
  }
}
